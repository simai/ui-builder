"use strict";

// SIMAI Framework Pro as a product (deprecated: SIMAI Framework Pro is dropped,
// and its four components move into a product's own package; see
// docs/developer/product-packages.md). Kept so ui-source-pro builds and
// publishes unchanged until the move: the overlay and the package rule file
// are the generic product-package ones (libs/packageProduct.js) with the
// package name `pro`, the four fixed component folders and Pro's own rule-file
// header, so a Pro build is byte-identical to the one this file used to make.

const {
    OVERLAY_DIRECTORIES,
    RULE_FILE,
    SOURCE_LOCK,
    collectPackageRules,
    materializePackageOverlay,
    materializePackageRule,
    renderPackageRuleFile: renderGenericPackageRuleFile,
    sha256,
    validateSourceLock,
} = require("./packageProduct");

const fs = require("node:fs");
const path = require("node:path");

const PRO_PACKAGE = "pro";
const PRO_COMPONENTS = Object.freeze(["admin-menu", "data-view", "property-view", "table"]);
const PRO_SOURCE_LOCK = SOURCE_LOCK;
const PRO_SOURCE_LOCK_SCHEMA = "simai.framework-pro.source-lock.v1";
const PRO_RULE_FILE_HEADER = Object.freeze([
    "// SIMAI Framework Pro: the package rule file. The Loader fetches it from",
    "// <base>/rule.js for a page that declares SF_BOOT_CONFIG.packages.pro.",
    "// Generated by ui-builder (the pro product) from smart/*/rule.js; not edited.",
]);
const PRO_PACKAGE_DEFINITION = Object.freeze({
    components: PRO_COMPONENTS,
    header: PRO_RULE_FILE_HEADER,
    name: PRO_PACKAGE,
});

function readProSourceLock(proRoot)
{
    const lock = validateSourceLock(
        JSON.parse(fs.readFileSync(path.join(proRoot, PRO_SOURCE_LOCK), "utf8")),
        PRO_SOURCE_LOCK,
    );

    if (lock.schema !== PRO_SOURCE_LOCK_SCHEMA)
    {
        throw new Error(`${PRO_SOURCE_LOCK}: schema must be ${PRO_SOURCE_LOCK_SCHEMA}`);
    }

    return lock;
}

/**
 * Lay out ui-source at the pinned revision and ui-source-pro at `proRevision`
 * over it (libs/packageProduct.js materializePackageOverlay, the repository
 * root as the package path, the four Pro folders exactly).
 */
function materializeProOverlay({ overlayRoot, proRevision = "HEAD", proRoot, uiSourceRoot })
{
    const result = materializePackageOverlay({
        components: PRO_COMPONENTS,
        overlayRoot,
        packageName: PRO_PACKAGE,
        repositoryRoot: proRoot,
        revision: proRevision,
        uiSourceRoot,
    });

    return {
        laid_files: result.laid_files,
        pro_revision: result.package_revision,
        source_revision: result.source_revision,
    };
}

/** The rules the Pro components' own rule.js files write, by rule name. */
function collectProRules(sourceRoot)
{
    return collectPackageRules(sourceRoot, PRO_COMPONENTS);
}

function renderPackageRuleFile(rules)
{
    return renderGenericPackageRuleFile(PRO_PACKAGE, rules, PRO_RULE_FILE_HEADER);
}

function materializeProPackageRule(plan)
{
    return materializePackageRule(plan, PRO_PACKAGE_DEFINITION);
}

module.exports = {
    OVERLAY_DIRECTORIES,
    PRO_COMPONENTS,
    PRO_PACKAGE,
    PRO_PACKAGE_DEFINITION,
    PRO_SOURCE_LOCK,
    PRO_SOURCE_LOCK_SCHEMA,
    RULE_FILE,
    collectProRules,
    materializeProOverlay,
    materializeProPackageRule,
    readProSourceLock,
    renderPackageRuleFile,
    sha256,
};
