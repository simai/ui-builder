"use strict";

// End to end: a tiny component package in a subdirectory of a product
// repository, over a tiny ui-source, built by the CLI and by the Node API
// into a configured output path. Each build prepares frozen dependency
// runtimes, so this suite needs the Yarn cache or the network.

const assert = require("node:assert/strict");
const crypto = require("node:crypto");
const { spawnSync } = require("node:child_process");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const test = require("node:test");

const api = require("../../libs/api");

const CLI = path.resolve(__dirname, "../../bin/sf-build.js");
const TIMEOUT = 10 * 60 * 1000;

function git(root, ...args)
{
    const result = spawnSync("git", ["-C", root, "-c", "user.name=test", "-c", "user.email=test@example.invalid", ...args], { encoding: "utf8" });
    assert.equal(result.status, 0, result.stderr);
    return result.stdout.trim();
}

function repository(root, files)
{
    for (const [relative, content] of Object.entries(files))
    {
        fs.mkdirSync(path.dirname(path.join(root, relative)), { recursive: true });
        fs.writeFileSync(path.join(root, relative), content);
    }

    git(root, "init", "-q");
    git(root, "add", "-A");
    git(root, "commit", "-q", "-m", "fixture");
    return git(root, "rev-parse", "HEAD");
}

function sha256(value)
{
    return crypto.createHash("sha256").update(value).digest("hex");
}

function fixture()
{
    const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "sf-build-e2e-")));
    const uiSource = path.join(root, "ui-source");
    const product = path.join(root, "acme");
    const pin = repository(uiSource, {
        "package.json": `${JSON.stringify({ name: "fixture-ui-source", private: true, version: "0.0.0" })}\n`,
        "yarn.lock": "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n\n",
        "src/smart/helpers/dom.js": "export const dom = 1;\n",
    });
    repository(product, {
        "sf-build.config.json": `${JSON.stringify({
            schema: "simai.sf-build.config.v1",
            package: { name: "acme", kind: "components", path: "resources/ui", repository: "example/acme" },
            framework: { source: "../ui-source" },
            out: "public/acme-ui",
        }, null, 2)}\n`,
        "app/server.php": "<?php\n",
        "resources/ui/package.json": `${JSON.stringify({ name: "@example/acme-ui", private: true, license: "LicenseRef-Acme-Commercial" })}\n`,
        "resources/ui/framework.lock.json": `${JSON.stringify({
            schema: "simai.framework.product-package-source-lock.v1",
            package: "acme",
            source: { repository: "simai/ui-source", revision: pin },
        })}\n`,
        "resources/ui/src/smart/widget/index.js": 'import { dom } from "../helpers/dom";\nimport "./scss/widget.scss";\nexport default class Widget { value() { return dom; } }\n',
        "resources/ui/src/smart/widget/scss/widget.scss": ".sf-widget { display: block; margin-inline-start: 4px; }\n",
        "resources/ui/src/smart/widget/rule.js": 'SF.RuleLoader["cl-widget"] = {tags: ["sf-widget"], type: "smart", mode: "smart", js: true, css: true, relation: []};\n',
    });
    return { pin, product, root, uiSource };
}

function sfBuild(args, cwd)
{
    const result = spawnSync(process.execPath, [CLI, ...args, "--json"], {
        cwd,
        encoding: "utf8",
        env: { ...process.env, SF_BUILD_UI: "", SF_BUILD_UI_SOURCE: "" },
        maxBuffer: 64 * 1024 * 1024,
    });

    return { status: result.status, stderr: result.stderr, value: JSON.parse(result.stdout) };
}

test("sf-build package lays a package, its receipt and its archive at the configured output path", { timeout: TIMEOUT }, async () => {
    const { pin, product, root, uiSource } = fixture();

    try
    {
        // The configuration is found in the working directory; out comes from it.
        const built = sfBuild(["package"], product);
        assert.equal(built.status, 0, JSON.stringify(built.value.error));
        const result = built.value;
        const out = path.join(product, "public/acme-ui");
        assert.equal(result.status, "PASS");
        assert.equal(result.exit_code, 0);
        assert.equal(result.package, "acme");
        assert.equal(result.kind, "components");
        assert.equal(result.config, path.join(product, "sf-build.config.json"));
        assert.equal(result.source_revision, pin);
        assert.deepEqual(result.components, ["widget"]);
        assert.deepEqual(result.package_source, { path: "resources/ui", repository: "example/acme", revision: git(product, "rev-parse", "HEAD") });
        assert.equal(result.package_reference, "not-checked");
        assert.deepEqual(result.out, {
            archive: path.join(out, "package-acme.tar"),
            receipt: path.join(out, "package-receipt.json"),
            root: out,
            runtime: path.join(out, "smart"),
        });
        assert.equal(result.workspace.kept, false);
        assert.ok(!fs.existsSync(path.dirname(result.workspace.root)), "the temporary workspace is removed");

        assert.deepEqual(fs.readdirSync(out).sort(), ["package-acme.tar", "package-receipt.json", "smart"]);
        assert.deepEqual(fs.readdirSync(path.join(out, "smart")).sort(), ["rule.js", "rule.js.gz", "widget"]);
        assert.match(fs.readFileSync(path.join(out, "smart/rule.js"), "utf8"), /SF\.RuleLoader\.registerPackage\("acme", \{/u);
        const receipt = JSON.parse(fs.readFileSync(path.join(out, "package-receipt.json"), "utf8"));
        assert.equal(receipt.package, "acme");
        assert.deepEqual(receipt.licence, { ref: "LicenseRef-Acme-Commercial" });
        assert.equal(receipt.output.archive_sha256, result.output.archive_sha256);
        assert.equal(receipt.output.manifest_sha256, result.output.manifest_sha256);
        assert.equal(sha256(fs.readFileSync(path.join(out, "package-acme.tar"))), receipt.output.archive_sha256);

        for (const item of receipt.files)
        {
            assert.equal(sha256(fs.readFileSync(path.join(out, item.path))), item.sha256, item.path);
        }

        // An earlier output is not replaced unless asked; the check runs before any build.
        const conflict = sfBuild(["package"], product);
        assert.equal(conflict.status, 2);
        assert.equal(conflict.value.error.code, "OUT_CONFLICT");

        // A directory sf-build did not lay is never replaced.
        const foreign = path.join(root, "foreign");
        fs.mkdirSync(foreign);
        fs.writeFileSync(path.join(foreign, "keep.txt"), "mine\n");
        const refused = sfBuild(["package", "--out", foreign, "--replace-out"], product);
        assert.equal(refused.value.error.code, "OUT_CONFLICT");
        assert.match(refused.value.error.message, /holds no package-receipt\.json/u);
        assert.equal(fs.readFileSync(path.join(foreign, "keep.txt"), "utf8"), "mine\n");

        // The Node API, with explicit options over the file, rebuilds the same bytes.
        const progress = [];
        const again = await api.buildPackage({
            config: path.join(product, "sf-build.config.json"),
            env: {},
            onProgress: message => progress.push(message),
            replaceOut: true,
            uiSource,
        });
        assert.equal(again.status, "PASS", JSON.stringify(again.error));
        assert.equal(again.output.archive_sha256, result.output.archive_sha256);
        assert.equal(again.output.manifest_sha256, result.output.manifest_sha256);
        assert.equal(progress.length, 3);

        // verify keeps a named workspace; receipt lays a package from it elsewhere.
        const workspace = path.join(root, "workspace");
        const verified = await api.verifyPackage({ cwd: product, env: {}, workspace });
        assert.equal(verified.status, "PASS", JSON.stringify(verified.error));
        assert.equal(verified.workspace.kept, true);
        assert.equal(verified.output.manifest_sha256, result.output.manifest_sha256);
        assert.ok(!fs.existsSync(path.join(workspace, "package-receipt.json")));

        const elsewhere = path.join(root, "elsewhere");
        const receipted = sfBuild(["receipt", "--report", path.join(workspace, "report.json"), "--out", elsewhere], root);
        assert.equal(receipted.status, 0, JSON.stringify(receipted.value.error));
        assert.equal(receipted.value.output.archive_sha256, result.output.archive_sha256);
        assert.deepEqual(fs.readdirSync(elsewhere).sort(), ["package-acme.tar", "package-receipt.json", "smart"]);
    }
    finally
    {
        fs.rmSync(root, { force: true, recursive: true });
    }
});

test("a failed package build exits 1 and keeps its workspace for diagnosis", { timeout: TIMEOUT }, async () => {
    const { product, root, uiSource } = fixture();

    try
    {
        fs.writeFileSync(path.join(product, "resources/ui/src/smart/widget/index.js"), 'import "./missing";\n');
        git(product, "commit", "-q", "-am", "break the widget");
        const failed = sfBuild(["package", "--ui-source", uiSource, "--workspace", path.join(root, "workspace")], product);
        assert.equal(failed.status, 1);
        assert.equal(failed.value.error.code, "BUILD_FAILED");
        assert.equal(failed.value.workspace.kept, true);
        assert.ok(fs.existsSync(path.join(root, "workspace/report.json")));
        assert.ok(!fs.existsSync(path.join(product, "public")), "nothing is laid");
    }
    finally
    {
        fs.rmSync(root, { force: true, recursive: true });
    }
});
