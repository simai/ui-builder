"use strict";

// A package's shared core (libs/packageCore.js): two components of a tiny
// package share one helper folder, declared as the package core in its
// package.json (simai.core). The build makes the core one bundle of its own,
// the components take it from the page's runtime instead of carrying a copy,
// and the rule file relates them to it. Each build prepares frozen dependency
// runtimes, so this suite needs the Yarn cache or the network.

const assert = require("node:assert/strict");
const { spawnSync } = require("node:child_process");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const test = require("node:test");

const { readPackageRuleFile } = require("../../libs/packageProduct");
const { coreModuleFor } = require("../../libs/packageCore");

const VERIFY = path.resolve(__dirname, "../../scripts/verify-package-reproducibility.cjs");
const RECEIPT = path.resolve(__dirname, "../../scripts/write-package-receipt.py");
const TIMEOUT = 10 * 60 * 1000;
// What the core's code says, once per copy of it in a bundle.
const MARK = "fixture-core-scale-body";

function git(root, ...args)
{
    const result = spawnSync("git", ["-C", root, "-c", "user.name=test", "-c", "user.email=test@example.invalid", ...args], { encoding: "utf8" });
    assert.equal(result.status, 0, result.stderr);
    return result.stdout.trim();
}

function write(root, files)
{
    for (const [relative, content] of Object.entries(files))
    {
        if (content === null)
        {
            fs.rmSync(path.join(root, relative), { force: true });
            continue;
        }
        fs.mkdirSync(path.dirname(path.join(root, relative)), { recursive: true });
        fs.writeFileSync(path.join(root, relative), content);
    }
}

function commit(root, files)
{
    write(root, files);
    if (!fs.existsSync(path.join(root, ".git"))) git(root, "init", "-q");
    git(root, "add", "-A");
    git(root, "commit", "-q", "-m", "fixture");
    return git(root, "rev-parse", "HEAD");
}

const PACKAGE_MODULES = {
    id: "<package>/<module>",
    register: "SF.runtimeModule.register(<package>, <abi>, {<module>: <namespace>})",
    reserved_namespaces: ["lit"],
};

function uiSource(root, contract = { schema: "simai.framework.shared-runtime", version: 1, abi: 1, package_modules: PACKAGE_MODULES })
{
    const directory = path.join(root, "ui-source");
    return commit(directory, {
        "package.json": `${JSON.stringify({ name: "fixture-ui-source", private: true, version: "0.0.0" })}\n`,
        "yarn.lock": "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n\n",
        "src/smart/helpers/dom.js": "export const dom = 1;\n",
        "src/core/contracts/shared-runtime.v1.json": `${JSON.stringify(contract)}\n`,
    });
}

const rule = (folder, relation) => `SF.RuleLoader["cl-${folder}"] = {tags: ["sf-${folder}"], type: "smart", mode: "smart", js: true, css: false, relation: ${JSON.stringify(relation)}};\n`;

function packageFiles(pin, { core = { folder: "kit-core", abi: 1 }, relate = true } = {})
{
    const relation = relate && core ? [{ name: `cl-${core.folder}` }] : [];
    return {
        "resources/ui/package.json": `${JSON.stringify({ name: "@example/acme-ui", private: true, license: "Apache-2.0", ...(core ? { simai: { core } } : {}) })}\n`,
        "resources/ui/framework.lock.json": `${JSON.stringify({ schema: "simai.framework.product-package-source-lock.v1", package: "acme", source: { repository: "simai/ui-source", revision: pin } })}\n`,
        "resources/ui/src/smart/kit-core/scale.js": `export function linear(value) { return ["${MARK}", value * 2]; }\nexport const unit = 10;\n`,
        "resources/ui/src/smart/kit-core/format.js": 'import { unit } from "./scale.js";\nexport const format = (value) => `${value}/${unit}`;\n',
        "resources/ui/src/smart/kit-a/index.js": 'import { linear } from "../kit-core/scale.js";\nimport { dom } from "../helpers/dom";\nexport default () => [linear(1), dom];\n',
        "resources/ui/src/smart/kit-a/rule.js": rule("kit-a", relation),
        "resources/ui/src/smart/kit-b/index.js": 'import { linear } from "../kit-core/scale";\nimport { format } from "../kit-core/format.js";\nexport default () => format(linear(2)[1]);\n',
        "resources/ui/src/smart/kit-b/rule.js": rule("kit-b", relation),
    };
}

function verify(root, product, name)
{
    const workspace = path.join(root, name);
    const result = spawnSync(process.execPath, [VERIFY, path.join(product, "resources/ui"), path.join(root, "ui-source"), workspace, "--package", "acme"], {
        encoding: "utf8",
        maxBuffer: 64 * 1024 * 1024,
    });
    const report = JSON.parse(fs.readFileSync(path.join(workspace, "report.json"), "utf8"));
    return { report, result, workspace, output: path.join(workspace, "wave-1/output/package/acme/smart") };
}

const read = (output, relative) => fs.readFileSync(path.join(output, relative), "utf8");
const count = (text, needle) => text.split(needle).length - 1;

test("a component's import from the core folder is the core's module name, and nothing else is", () => {
    const core = { folder: "kit-core", abi: 1, name: "acme" };
    const root = fs.realpathSync(os.tmpdir());
    const source = path.join(root, "src");
    const issuer = path.join(source, "smart/kit-a/index.js");
    const context = path.join(source, "smart/kit-a");
    assert.equal(coreModuleFor({ context, request: "../kit-core/scale.js", issuer }, source, core), "scale");
    assert.equal(coreModuleFor({ context, request: "../kit-core/geo/projection", issuer }, source, core), "geo/projection");
    assert.equal(coreModuleFor({ context, request: "../kit-other/scale.js", issuer }, source, core), null);
    assert.equal(coreModuleFor({ context, request: "lit", issuer }, source, core), null);
    assert.equal(coreModuleFor({ context, request: "../kit-core/x.js", issuer: path.join(root, "node_modules/x/i.js") }, source, core), null);
});

test("the package core is built once and the components take it from the runtime", { timeout: TIMEOUT }, async () => {
    const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "sf-package-core-")));
    try
    {
        const pin = uiSource(root);
        const product = path.join(root, "acme");
        commit(product, packageFiles(pin));
        const { report, result, output, workspace } = verify(root, product, "shared");
        assert.equal(result.status, 0, `${result.stderr}\n${report.error || ""}`);
        assert.equal(report.status, "PASS");
        assert.equal(report.products.package.byte_identical, true);

        // The core is one bundle that registers both modules; the components
        // carry none of its code and ask the runtime for it.
        const coreBundle = read(output, "kit-core/js/kit-core.js");
        assert.equal(count(coreBundle, MARK), 1);
        assert.match(coreBundle, /lookup\.register\("acme", 1, modules\)/u);
        assert.match(coreBundle, /"format": _format_js__WEBPACK_IMPORTED_MODULE_0__,\n\s+"scale": _scale_js__WEBPACK_IMPORTED_MODULE_1__\n/u);
        for (const folder of ["kit-a", "kit-b"])
        {
            for (const file of [`${folder}/js/${folder}.js`, `${folder}/js/${folder}.min.js`])
            {
                const bundle = read(output, file);
                assert.equal(count(bundle, MARK), 0, `${file} carries the core`);
                assert.match(bundle, /globalThis\.SF\.runtimeModule\("acme\/scale", ?1\)/u, file);
            }
        }
        assert.match(read(output, "kit-b/js/kit-b.js"), /globalThis\.SF\.runtimeModule\("acme\/format", 1\)/u);
        assert.ok(fs.existsSync(path.join(output, "kit-core/js/kit-core.min.js.gz")));

        // The rule file: the core's tagless rule, which both components relate to.
        const { rules } = readPackageRuleFile(read(output, "rule.js"));
        assert.deepEqual(Object.keys(rules), ["cl-kit-a", "cl-kit-b", "cl-kit-core"]);
        assert.deepEqual(rules["cl-kit-core"], { css: false, js: true, mode: "smart", tags: [], type: "smart" });
        assert.deepEqual(rules["cl-kit-a"].relation, [{ name: "cl-kit-core" }]);

        // The generated entry is gone from the overlay the package's tests run in.
        assert.equal(fs.existsSync(path.join(workspace, "wave-1/overlay/src/smart/kit-core/index.js")), false);

        // The report and the receipt say what the components ask of the core.
        assert.deepEqual(report.components, ["kit-a", "kit-b"]);
        assert.deepEqual(report.core, {
            schema: "simai.framework.package-core-usage",
            version: 1,
            folder: "kit-core",
            rule: "cl-kit-core",
            abi: 1,
            id_prefix: "acme/",
            users: ["kit-a", "kit-b"],
            modules: { "acme/format": ["format"], "acme/scale": ["linear"] },
        });
        const receipt = spawnSync("python3", [RECEIPT, "--report", path.join(workspace, "report.json")], { encoding: "utf8" });
        assert.equal(receipt.status, 0, receipt.stderr);
        const value = JSON.parse(fs.readFileSync(path.join(workspace, "package-receipt.json"), "utf8"));
        assert.equal(value.core.script, "smart/kit-core/js/kit-core.js");
        assert.ok(value.required_files.some((item) => item.path === "smart/kit-core/js/kit-core.js"));
        assert.deepEqual(value.framework.runtime.modules, {}, "the package's own ids are not the runtime's");

        // Without the declaration the same package carries the core twice.
        commit(product, packageFiles(pin, { core: null }));
        const plain = verify(root, product, "plain");
        assert.equal(plain.result.status, 0, plain.report.error);
        assert.equal(count(read(plain.output, "kit-a/js/kit-a.js"), MARK), 1);
        assert.equal(count(read(plain.output, "kit-b/js/kit-b.js"), MARK), 1);
        assert.equal(fs.existsSync(path.join(plain.output, "kit-core")), false);
    }
    finally
    {
        fs.rmSync(root, { force: true, recursive: true });
    }
});

test("the build refuses a component that takes the core without relating to it, a live binding, a missing name and an old ui-source", { timeout: TIMEOUT }, async () => {
    const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "sf-package-core-refuse-")));
    const failure = (workspace) => {
        const diagnostics = path.join(workspace, "wave-1/diagnostics/package.json");
        return [diagnostics, `${diagnostics}.stats.json`]
            .filter((file) => fs.existsSync(file))
            .map((file) => fs.readFileSync(file, "utf8"))
            .join("\n") || JSON.parse(fs.readFileSync(path.join(workspace, "report.json"), "utf8")).error;
    };
    try
    {
        const pin = uiSource(root);
        const product = path.join(root, "acme");

        commit(product, packageFiles(pin, { relate: false }));
        let run = verify(root, product, "unrelated");
        assert.notEqual(run.result.status, 0);
        assert.match(failure(run.workspace), /cl-kit-a, cl-kit-b import the package core smart\/kit-core but do not relate to cl-kit-core/u);

        commit(product, { ...packageFiles(pin), "resources/ui/src/smart/kit-core/scale.js": `export let linear = () => "${MARK}";\nexport const unit = 1;\n` });
        run = verify(root, product, "live");
        assert.notEqual(run.result.status, 0);
        assert.match(failure(run.workspace), /exports a live binding \(export let\)/u);

        commit(product, { ...packageFiles(pin), "resources/ui/src/smart/kit-a/index.js": 'import { missing } from "../kit-core/scale.js";\nexport default () => missing;\n' });
        run = verify(root, product, "missing");
        assert.notEqual(run.result.status, 0);
        assert.match(failure(run.workspace), /imports \\?"missing\\?" from the package core module \\?"acme\/scale\\?", which does not export it/u);

        const old = uiSource(root, { schema: "simai.framework.shared-runtime", version: 1, abi: 1 });
        commit(product, packageFiles(old));
        run = verify(root, product, "old");
        assert.notEqual(run.result.status, 0);
        assert.match(failure(run.workspace), /the pinned ui-source has no package modules/u);
    }
    finally
    {
        fs.rmSync(root, { force: true, recursive: true });
    }
});
